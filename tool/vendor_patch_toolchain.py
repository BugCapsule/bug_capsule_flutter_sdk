#!/usr/bin/env python3
"""Embed first-party patch compiler sources from an immutable engine Git commit."""
import argparse
import base64
import gzip
import hashlib
import json
from pathlib import Path
import subprocess

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--engine-repo', type=Path, required=True)
p.add_argument('--engine-ref', required=True)
p.add_argument('--check', action='store_true')
a = p.parse_args()
root = Path(__file__).resolve().parents[1]
def git(*args):
    return subprocess.check_output(['git', '-C', str(a.engine_repo), *args])
revision = git('rev-parse', a.engine_ref + '^{commit}').decode().strip()
files = ['package.json', 'compiler/package.json', 'tools/bcpatch.ts',
         'tools/lib.ts', 'tools/provenance.ts', 'tools/classify.ts']
files += git('ls-tree', '-r', '--name-only', revision, 'compiler/src').decode().splitlines()
files = sorted(files)
if any(not f.endswith(('.ts', '.json')) for f in files):
    raise SystemExit('Unexpected compiler input; review the vendor allowlist')
contents = {f: git('show', revision + ':' + f) for f in files}
manifest = {'engineRepository': 'https://github.com/BugCapsule/bug_capsule_patch_enigne',
            'engineCommit': revision, 'nodeMinimumMajor': 24,
            'files': {f: {'sha256': hashlib.sha256(b).hexdigest(), 'bytes': len(b)}
                      for f, b in contents.items()}}
payload = json.dumps({f: base64.b64encode(b).decode() for f, b in contents.items()},
                     sort_keys=True, separators=(',', ':')).encode()
encoded = base64.b64encode(gzip.compress(payload, mtime=0)).decode()
dart = ('// Generated by tool/vendor_patch_toolchain.py; do not edit.\n'
        '// First-party compiler sources; provenance: patch_toolchain_manifest.json.\n'
        f"const bundledPatchEngineCommit = '{revision}';\n"
        'const bundledPatchToolchainBase64 =\n' +
        ''.join(f"    '{encoded[i:i+100]}'\n" for i in range(0, len(encoded), 100)) + ';\n')
outputs = {
    root / 'packages/bug_capsule/lib/src/cli/patch_toolchain_data.dart': dart,
    root / 'packages/bug_capsule/patch_toolchain_manifest.json': json.dumps(manifest, indent=2) + '\n',
}
for path, text in outputs.items():
    if a.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit(f'Vendored toolchain differs: {path.name}')
    else:
        path.write_text(text)
print(f'Verified {len(files)} compiler/tool inputs at {revision}' if a.check else
      f'Embedded {len(files)} compiler/tool inputs at {revision}')
