/// Riverpod (3.x) integration for BugCapsule.
///
/// Records provider initializations, updates, errors and disposals,
/// snapshots the value of registered providers into periodic checkpoints,
/// and restores it in replay.
///
/// ```dart
/// final bugCapsuleRiverpod = BugCapsuleRiverpod(states: [
///   BugCapsuleRiverpodState<Cart>(cartProvider, toJson: (c) => c.toJson(), fromJson: Cart.fromJson),
/// ]);
///
/// BugCapsule.init(
///   integrations: [bugCapsuleRiverpod, ...],
///   appRunner: () => runApp(ProviderScope(observers: [bugCapsuleRiverpod.observer], child: const MyApp())),
///   ...
/// );
/// ```
///
/// Providers are keyed `<id>#<n>`: the n-th time that provider was
/// initialized in the session, like BLoC instances. Replay restores a
/// periodic checkpoint by setting the state of each registered provider
/// right after it is initialized again.
library;

import 'dart:async';
import 'dart:convert';

import '../runtime/runtime.dart';
import 'package:riverpod/misc.dart';
import 'package:riverpod/riverpod.dart';

/// Serializer for the value of one provider (or every provider of a
/// family) whose value type is [T].
///
/// For `AsyncNotifierProvider` / `StreamNotifierProvider` / `FutureProvider`,
/// [T] is the data type, not `AsyncValue<T>`: only `AsyncData` is
/// snapshotted, and a restore sets `AsyncData(value)`.
class BugCapsuleRiverpodState<T> {
  BugCapsuleRiverpodState(
    this.provider, {
    String? id,
    required this.toJson,
    required this.fromJson,
    this.restore,
  }) : id =
           id ??
           provider.name ??
           (throw ArgumentError.value(
             provider,
             'provider',
             'give the provider a `name` or pass `id`',
           ));

  /// A provider, or a family to cover all of its providers.
  final ProviderOrFamily provider;

  /// Stable name used in checkpoint keys; defaults to the provider's `name`.
  final String id;

  final Object? Function(T value) toJson;
  final T Function(Map<String, Object?> json) fromJson;

  /// Sets the restored [value] on [provider] in [container]. Not needed for
  /// `NotifierProvider`, `AsyncNotifierProvider` and `StreamNotifierProvider`
  /// (and their families); required for other providers you want restored,
  /// such as those generated by `riverpod_generator`:
  /// `restore: (container, provider, value) => container.read(cartProvider.notifier).replace(value)`.
  final void Function(
    ProviderContainer container,
    ProviderBase<Object?> provider,
    T value,
  )?
  restore;

  bool matches(ProviderBase<Object?> p) =>
      p == provider || (p.from != null && p.from == provider);

  /// The JSON for [value], or [_unsettled] when an async provider has no
  /// data (loading or error).
  Object? encode(Object? value) => switch (value) {
    AsyncData(:final value) => toJson(value as T),
    AsyncValue() => _unsettled,
    _ => toJson(value as T),
  };

  void restoreInto(
    ProviderContainer container,
    ProviderBase<Object?> p,
    Map<String, Object?> json,
  ) {
    final value = fromJson(json);
    final custom = restore;
    if (custom != null) return custom(container, p, value);
    // Restoring is the one place an outside party must set a notifier's state.
    switch (p) {
      case NotifierProvider<Notifier<T>, T>():
        // ignore: invalid_use_of_protected_member, invalid_use_of_visible_for_testing_member
        container.read(p.notifier).state = value;
      case AsyncNotifierProvider<AsyncNotifier<T>, T>():
        // ignore: invalid_use_of_protected_member, invalid_use_of_visible_for_testing_member
        container.read(p.notifier).state = AsyncData(value);
      case StreamNotifierProvider<StreamNotifier<T>, T>():
        // ignore: invalid_use_of_protected_member, invalid_use_of_visible_for_testing_member
        container.read(p.notifier).state = AsyncData(value);
      default:
        throw UnsupportedError(
          '${p.runtimeType} cannot be restored without a `restore` callback',
        );
    }
  }
}

const _unsettled = Object();

class BugCapsuleRiverpod extends BugCapsuleIntegration {
  BugCapsuleRiverpod({
    this.states = const [],
    this.recordStateData,
    this.maxStateBytes = 64 * 1024,
    this.treatErrorsAsFailures = true,
  });

  final List<BugCapsuleRiverpodState<Object?>> states;

  /// Include serialized values in `riverpod.add` / `riverpod.update` events.
  /// Defaults to true except in production.
  final bool? recordStateData;
  final int maxStateBytes;

  /// Report provider errors (a throwing `build`, a failed future or stream)
  /// as failures, deduplicated with uncaught errors.
  final bool treatErrorsAsFailures;

  /// Pass to `ProviderScope(observers: [...])` or `ProviderContainer`.
  late final ProviderObserver observer = _BugCapsuleProviderObserver(this);

  BugCapsuleSession? _session;
  final Map<String, _Mounted> _live = {};
  final Map<String, int> _ordinals = {};
  final Map<(ProviderContainer, ProviderBase<Object?>), String> _keys = {};
  final Set<String> _added = {};
  Map<String, Object?> _restoreData = const {};
  final Set<String> _unregistered = {};
  final Set<String> _oversized = {};

  @override
  String get name => 'riverpod';

  bool get _withData =>
      recordStateData ?? _session!.mode != CaptureMode.production;

  @override
  Future<void> setUp(BugCapsuleSession session) async => _session = session;

  BugCapsuleRiverpodState<Object?>? _registration(
    ProviderBase<Object?> provider,
  ) {
    for (final s in states) {
      if (s.matches(provider)) return s;
    }
    return null;
  }

  /// Providers whose state lives in a notifier and is lost unless
  /// registered. Derived providers (`Provider`, `FutureProvider`, ...) are
  /// recomputed in replay.
  static bool _holdsState(ProviderBase<Object?> p) =>
      p is NotifierProvider<Notifier<Object?>, Object?> ||
      p is AsyncNotifierProvider<AsyncNotifier<Object?>, Object?> ||
      p is StreamNotifierProvider<StreamNotifier<Object?>, Object?>;

  String _label(
    ProviderBase<Object?> p,
    BugCapsuleRiverpodState<Object?>? registration,
  ) {
    final base =
        registration?.id ?? p.from?.name ?? p.name ?? '${p.runtimeType}';
    if (p.from == null) return base;
    return '$base(${_session!.redactor.scrubText('${p.argument}')})';
  }

  @override
  Object? snapshot(CheckpointKind kind) {
    // A launch checkpoint is taken before any provider is initialized;
    // replay re-executes the session instead of injecting state.
    if (kind == CheckpointKind.launch) return null;
    final session = _session;
    if (session == null) return null;
    // Dispose events also fire on rebuilds; only the container knows whether
    // a provider is still mounted.
    _live.removeWhere((_, mounted) => !mounted.exists);
    final data = <String, Object?>{};
    for (final MapEntry(:key, value: mounted) in _live.entries) {
      final registration = mounted.registration;
      if (registration == null) {
        if (_holdsState(mounted.provider)) {
          _unregistered.add(_label(mounted.provider, null));
        }
        continue;
      }
      final encoded = registration.encode(mounted.value);
      final entry = <String, Object?>{
        'provider': _label(mounted.provider, registration),
        'stateType': mounted.value.runtimeType.toString(),
      };
      if (!identical(encoded, _unsettled)) {
        final json = session.redactor.redactJson(encoded);
        if (jsonEncode(json).length > maxStateBytes) {
          _oversized.add(key);
          continue;
        }
        entry['state'] = json;
      }
      data[key] = entry;
    }
    return data;
  }

  @override
  Future<void> restore(Object? data, BugCapsuleSession session) async {
    if (data is Map) _restoreData = data.cast<String, Object?>();
  }

  @override
  void describeEligibility(
    EligibilityBuilder eligibility,
    RecordedWindow window,
  ) {
    if (window.checkpoint.kind != CheckpointKind.periodic) return;
    for (final label in _unregistered) {
      eligibility.missing(
        'riverpod.state',
        '$label has no BugCapsuleRiverpodState serializer',
      );
    }
    for (final key in _oversized) {
      eligibility.missing(
        'riverpod.state',
        '$key state exceeds $maxStateBytes bytes; add a projection',
      );
    }
  }

  // ----------------------------------------------------------------- events

  String _keyOf(ProviderObserverContext context) =>
      _keys[(context.container, context.provider)] ?? _assignKey(context);

  /// `<id>#<n>`: the n-th initialization of this provider in the session.
  /// Deterministic as long as replay follows the same path.
  String _assignKey(ProviderObserverContext context) {
    final previous = _keys[(context.container, context.provider)];
    if (previous != null) _live.remove(previous);
    final label = _label(context.provider, _registration(context.provider));
    final n = _ordinals.update(label, (v) => v + 1, ifAbsent: () => 0);
    return _keys[(context.container, context.provider)] = '$label#$n';
  }

  Map<String, Object?> _describe(
    String key,
    ProviderObserverContext context,
    Object? value,
  ) {
    final session = _session!;
    final registration = _registration(context.provider);
    Object? data;
    if (_withData && registration != null) {
      try {
        final encoded = registration.encode(value);
        if (!identical(encoded, _unsettled)) {
          data = session.redactor.redactJson(encoded);
          if (jsonEncode(data).length > maxStateBytes) data = null;
        }
      } catch (_) {
        data = null;
      }
    }
    return {
      'provider': _label(context.provider, registration),
      'key': key,
      'state': value.runtimeType.toString(),
      'data': ?data,
    };
  }

  void _onAdd(ProviderObserverContext context, Object? value) {
    final session = _session;
    if (session == null) return;
    session.replay?.activity();
    // A provider whose build throws may report the error before it is added.
    final existing = _keys[(context.container, context.provider)];
    final key = existing != null && !_added.contains(existing)
        ? existing
        : _assignKey(context);
    _added.add(key);
    final registration = _registration(context.provider);
    _live[key] = _Mounted(
      context.container,
      context.provider,
      registration,
      value,
    );
    if (session.isRecording) {
      session.record(EventTypes.riverpodAdd, _describe(key, context, value));
    }

    final replay = session.replay;
    final saved = _restoreData[key];
    if (replay == null || saved == null) return;
    if (saved is! Map || saved['state'] is! Map) {
      // Redacted on device, not serializable, or an async provider that had
      // no data at the checkpoint.
      replay.diverge('riverpod.unrestored', '$key: state was not captured');
      return;
    }
    if (registration == null) {
      replay.diverge(
        'riverpod.unrestored',
        '$key has no BugCapsuleRiverpodState serializer',
      );
      return;
    }
    // Providers may not modify other providers while they initialize.
    // Restore once this initialization (and the build that caused it) ends.
    final container = context.container;
    final provider = context.provider;
    scheduleMicrotask(() {
      try {
        registration.restoreInto(
          container,
          provider,
          (saved['state'] as Map).cast<String, Object?>(),
        );
      } catch (e) {
        replay.diverge('riverpod.unrestored', '$key: $e');
      }
    });
  }

  void _onUpdate(ProviderObserverContext context, Object? value) {
    final session = _session;
    if (session == null) return;
    session.replay?.activity();
    final key = _keyOf(context);
    final mounted = _live[key];
    if (mounted != null) {
      mounted.value = value;
    } else {
      _live[key] = _Mounted(
        context.container,
        context.provider,
        _registration(context.provider),
        value,
      );
    }
    if (session.isRecording) {
      session.record(EventTypes.riverpodUpdate, _describe(key, context, value));
    }
  }

  void _onFail(
    ProviderObserverContext context,
    Object error,
    StackTrace stackTrace,
  ) {
    final session = _session;
    if (session == null) return;
    session.replay?.activity();
    session.record(EventTypes.riverpodError, {
      'provider': _label(context.provider, _registration(context.provider)),
      'key': _keyOf(context),
      'error': session.redactor.scrubText('$error'),
    });
    if (treatErrorsAsFailures) session.reportError(error, stackTrace);
  }

  void _onDispose(ProviderObserverContext context) {
    final session = _session;
    if (session == null) return;
    session.record(EventTypes.riverpodDispose, {
      'provider': _label(context.provider, _registration(context.provider)),
      'key': _keyOf(context),
    });
  }
}

class _Mounted {
  _Mounted(this.container, this.provider, this.registration, this.value);

  final ProviderContainer container;
  final ProviderBase<Object?> provider;
  final BugCapsuleRiverpodState<Object?>? registration;
  Object? value;

  bool get exists {
    try {
      return container.exists(provider);
    } catch (_) {
      return false; // container disposed
    }
  }
}

/// Recording bugs must never reach the app through Riverpod's observer.
final class _BugCapsuleProviderObserver extends ProviderObserver {
  _BugCapsuleProviderObserver(this._integration);

  final BugCapsuleRiverpod _integration;

  static void _guard(void Function() body) {
    try {
      body();
    } catch (_) {}
  }

  @override
  void didAddProvider(ProviderObserverContext context, Object? value) =>
      _guard(() => _integration._onAdd(context, value));

  @override
  void didUpdateProvider(
    ProviderObserverContext context,
    Object? previousValue,
    Object? newValue,
  ) => _guard(() => _integration._onUpdate(context, newValue));

  @override
  void providerDidFail(
    ProviderObserverContext context,
    Object error,
    StackTrace stackTrace,
  ) => _guard(() => _integration._onFail(context, error, stackTrace));

  @override
  void didDisposeProvider(ProviderObserverContext context) =>
      _guard(() => _integration._onDispose(context));
}
